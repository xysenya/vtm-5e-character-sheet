const CUSTOM_PREDATOR_TYPES_STORAGE_KEY = 'vtm_v5_custom_predator_types_list';

export const loadSavedCustomPredatorTypes = (): CustomPredatorTypeEntry[] => {
  try {
    const raw = localStorage.getItem(CUSTOM_PREDATOR_TYPES_STORAGE_KEY);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch (err) {
    console.error('Failed to load custom predator types from storage', err);
    return [];
  }
};

export const saveCustomPredatorTypesToStorage = (types: CustomPredatorTypeEntry[]) => {
  try {
    localStorage.setItem(CUSTOM_PREDATOR_TYPES_STORAGE_KEY, JSON.stringify(types));
  } catch (err) {
    console.error('Failed to save custom predator types to storage', err);
  }
};
